"""Markdown scientific report for the physics activation atlas smoke."""

from __future__ import annotations

import json
from pathlib import Path


def write_report(out: Path, analysis: dict) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    p = out / "REPORT.md"
    lines = [
        "# Physics activation atlas — smoke report",
        "",
        "Exploratory atlas of overlapping locally Euclidean charts on dense Physics ViT activations.",
        "Does **not** prove global activation topology. No global VAE. No physics labels.",
        "",
        "## Decision summary",
        "",
    ]
    for k, v in analysis.get("decisions", {}).items():
        lines.append(f"- **{k}**: `{v}`")
    lines += [
        "",
        "## Data / preprocessing",
        "",
        "```json",
        json.dumps(analysis.get("data", {}), indent=2)[:4000],
        "```",
        "",
        "## Atlas construction",
        "",
        "```json",
        json.dumps(analysis.get("charts", {}), indent=2)[:4000],
        "```",
        "",
        "## Local dimension",
        "",
        "```json",
        json.dumps(analysis.get("dimension", {}), indent=2)[:4000],
        "```",
        "",
        "## Synthetic validation",
        "",
        "```json",
        json.dumps(analysis.get("synthetic", {}), indent=2)[:4000],
        "```",
        "",
        "## Decoder vs PCA",
        "",
        "```json",
        json.dumps(analysis.get("decoders", {}), indent=2)[:4000],
        "```",
        "",
        "## Jacobians",
        "",
        "```json",
        json.dumps(analysis.get("jacobians", {}), indent=2)[:4000],
        "```",
        "",
        "## Priors",
        "",
        "```json",
        json.dumps(analysis.get("priors", {}), indent=2)[:4000],
        "```",
        "",
        "## Overlaps",
        "",
        "```json",
        json.dumps(analysis.get("overlaps", {}), indent=2)[:4000],
        "```",
        "",
        "## Nerve (exploratory)",
        "",
        "```json",
        json.dumps(analysis.get("nerve", {}), indent=2)[:4000],
        "```",
        "",
        "## Patch topology (exploratory)",
        "",
        "```json",
        json.dumps(analysis.get("patch_topology", {}), indent=2)[:4000],
        "```",
        "",
        "## Boundary",
        "",
        "```json",
        json.dumps(analysis.get("boundary", {}), indent=2)[:4000],
        "```",
        "",
        "## Curvature",
        "",
        "```json",
        json.dumps(analysis.get("curvature", {}), indent=2)[:4000],
        "```",
        "",
        "## Runtime",
        "",
        "```json",
        json.dumps(analysis.get("runtime", {}), indent=2),
        "```",
        "",
        "## Conservative interpretation",
        "",
        analysis.get("interpretation", ""),
        "",
        "## Next command (not run)",
        "",
        "```bash",
        analysis.get("next_command", ""),
        "```",
        "",
    ]
    p.write_text("\n".join(lines))
    (out / "analysis.json").write_text(json.dumps(analysis, indent=2, default=str))
    return p
